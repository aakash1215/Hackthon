#!/usr/bin/env bash
# KOALA audit of the open-weight model (https://github.com/DomAiynLabs/KOALA, Apache-2.0).
# Writes MODEL_AUDIT.md in the repo root, plus JSON/HTML/manifest in docs/model-audit/.
#
#   bash scripts/audit_model.sh            # static docs audit + live probes if llama-server is up
#   bash scripts/audit_model.sh --static   # docs only (no model calls)
#   PROBE_RUNS=3 bash scripts/audit_model.sh   # more runs per probe (slow on CPU)
#
# KOALA lives in its own venv (.venv-koala, gitignored), so it never touches the hub's dependencies.
# The probes hit only the local open-weight model at LLM_BASE_URL — never the optional ChatGPT engine.
set -eu
cd "$(dirname "$0")/.."

KOALA_REF="${KOALA_REF:-c9a9c1b13e172163a650828cddeb76fc8044c6a8}"  # pinned commit (v0.2.0, 14 Aug 2026)
VENV=.venv-koala
OUT=docs/model-audit
FRAMEWORKS="${FRAMEWORKS:-india_dpdp,eu_ai_act,nist_ai_rmf}"

if [ -x "$VENV/Scripts/koala.exe" ]; then KOALA="$VENV/Scripts/koala.exe"; else KOALA="$VENV/bin/koala"; fi
if [ ! -x "$KOALA" ]; then
  echo "== installing KOALA @ ${KOALA_REF:0:7} into $VENV"
  uv venv -q -p 3.12 "$VENV"
  if [ -x "$VENV/Scripts/python.exe" ]; then PY="$VENV/Scripts/python.exe"; else PY="$VENV/bin/python"; fi
  # Editable install from a pinned clone, as KOALA's README does: its wheel build fails on newer hatchling
  # ("A second file is being added to the wheel archive": packs/*.yaml are force-included twice).
  git clone -q https://github.com/DomAiynLabs/KOALA "$VENV/src/koala"
  git -C "$VENV/src/koala" checkout -q "$KOALA_REF"
  uv pip install -q --python "$PY" -e "$VENV/src/koala"
  if [ -x "$VENV/Scripts/koala.exe" ]; then KOALA="$VENV/Scripts/koala.exe"; else KOALA="$VENV/bin/koala"; fi
fi

LLM_BASE_URL="$(grep -E '^LLM_BASE_URL=' .env 2>/dev/null | cut -d= -f2- | tr -d '\r' || true)"
LLM_BASE_URL="${LLM_BASE_URL:-http://127.0.0.1:8080/v1}"
MODE="static (documentation only)"
TARGET=()
if [ "${1:-}" != "--static" ]; then
  if curl -sf -m 5 "$LLM_BASE_URL/models" >/dev/null; then
    MODE="static + dynamic probes against $LLM_BASE_URL (${PROBE_RUNS:-1} run(s) per probe)"
    TARGET=(--target "openai:$LLM_BASE_URL" --probe-runs "${PROBE_RUNS:-1}")
    export KOALA_REQUEST_TIMEOUT_S="${KOALA_REQUEST_TIMEOUT_S:-300}"  # 1.7B on a CPU is slow
  else
    echo "== llama-server not reachable at $LLM_BASE_URL: static audit only (start it: bash scripts/start_llm.sh cpu)"
  fi
fi

echo "== auditing ($MODE)"
mkdir -p "$OUT"
set +e
"$KOALA" audit audit --frameworks "$FRAMEWORKS" --attest audit/attestations.yaml \
  --output-dir "$OUT" --formats json,md,html --manifest "${TARGET[@]}"
rc=$?
set -e
[ -f "$OUT/koala_report.md" ] || { echo "KOALA produced no report (exit $rc)"; exit 1; }

{
  echo "# Model audit (KOALA)"
  echo
  echo "> Generated by \`bash scripts/audit_model.sh\` on $(date '+%Y-%m-%d %H:%M %Z') with"
  echo "> [KOALA](https://github.com/DomAiynLabs/KOALA) @ \`${KOALA_REF:0:7}\`. Mode: $MODE."
  echo "> Audited: the open-weight model and the documents in [\`audit/\`](audit/) (model card, privacy, security,"
  echo "> training data, changelog, attestations). **This is evidence and gap analysis, not legal certification.**"
  echo "> Full reports: [\`$OUT/\`]($OUT/) (JSON, HTML, SHA-256 manifest)."
  echo
  cat "$OUT/koala_report.md"
} > MODEL_AUDIT.md
echo "== wrote MODEL_AUDIT.md (koala exit $rc)"
